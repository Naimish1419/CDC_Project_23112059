import os
import math
import requests
import pandas as pd
from PIL import Image
from io import BytesIO
from concurrent.futures import ThreadPoolExecutor, as_completed
from tqdm import tqdm

# ===============================
# CONFIG
# ===============================
IMAGE_DIR = "sat_images_esri"
LOG_FILE = "image_download_log.csv"

ZOOM_LEVEL = 18
TILE_GRID = 3          # 3×3 tiles
OUT_SIZE = 224
MAX_WORKERS = 5        # DO NOT exceed 6 (ESRI throttles)

os.makedirs(IMAGE_DIR, exist_ok=True)

# ===============================
# UTILS
# ===============================
def latlon_to_tile(lat, lon, zoom):
    lat_rad = math.radians(lat)
    n = 2.0 ** zoom

    x = int((lon + 180.0) / 360.0 * n)
    y = int(
        (1.0 - math.log(math.tan(lat_rad) + 1 / math.cos(lat_rad)) / math.pi)
        / 2.0 * n
    )
    return x, y


def fetch_esri_tile(z, x, y):
    url = (
        "https://services.arcgisonline.com/ArcGIS/rest/services/"
        f"World_Imagery/MapServer/tile/{z}/{y}/{x}"
    )
    r = requests.get(url, timeout=10)
    r.raise_for_status()
    return Image.open(BytesIO(r.content)).convert("RGB")


def fetch_esri_stitched(lat, lon):
    cx, cy = latlon_to_tile(lat, lon, ZOOM_LEVEL)
    half = TILE_GRID // 2

    tiles = []
    for dy in range(-half, half + 1):
        row = []
        for dx in range(-half, half + 1):
            tile = fetch_esri_tile(ZOOM_LEVEL, cx + dx, cy + dy)
            row.append(tile)
        tiles.append(row)

    tile_size = tiles[0][0].size[0]
    full_size = tile_size * TILE_GRID
    stitched = Image.new("RGB", (full_size, full_size))

    for r in range(TILE_GRID):
        for c in range(TILE_GRID):
            stitched.paste(
                tiles[r][c],
                (c * tile_size, r * tile_size)
            )

    return stitched.resize((OUT_SIZE, OUT_SIZE))


# ===============================
# ROW PROCESSOR
# ===============================
def process_row(row):
    row_id = row["row_id"]
    out_path = os.path.join(IMAGE_DIR, f"{row_id}.png")

    if os.path.exists(out_path):
        return row_id, "skipped"

    try:
        img = fetch_esri_stitched(row["lat"], row["long"])
        img.save(out_path, format="PNG")
        return row_id, "saved"
    except Exception as e:
        return row_id, f"error: {str(e)}"


# ===============================
# MAIN
# ===============================
def main(df):
    # 🔒 Freeze row ↔ image mapping
    df = df.reset_index(drop=True)
    df["row_id"] = df.index

    print(f"Downloading {len(df)} images using {MAX_WORKERS} workers\n")

    results = []

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = [
            executor.submit(process_row, row)
            for _, row in df.iterrows()
        ]

        for f in tqdm(as_completed(futures), total=len(futures)):
            results.append(f.result())

    # Save audit log
    log_df = pd.DataFrame(results, columns=["row_id", "status"])
    log_df.to_csv(LOG_FILE, index=False)

    print("\nDownload completed.")
    print(f"Log saved to: {LOG_FILE}")
    print(f"Images saved in: {IMAGE_DIR}")


# ===============================
# RUN
# ===============================
main(df)

