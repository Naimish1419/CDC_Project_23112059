import os
import torch
import pandas as pd
import numpy as np
from PIL import Image
from tqdm import tqdm
from torchvision import models, transforms
from torchvision.models import ResNet50_Weights

# ===============================
# CONFIG
# ===============================
IMAGE_DIR = "sat_images_esri"
OUTPUT_FILE = "cnn_embeddings.npy"
META_FILE = "cnn_embedding_index.csv"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

# ===============================
# MODEL
# ===============================
model = models.resnet50(weights=ResNet50_Weights.DEFAULT)
model.fc = torch.nn.Identity()
model = model.to(DEVICE)
model.eval()

# ===============================
# TRANSFORMS (FIXED)
# ===============================
transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],   # ImageNet mean
        std=[0.229, 0.224, 0.225]     # ImageNet std
    )
])

# ===============================
# LOAD IMAGE LIST
# ===============================
image_files = sorted(
    [f for f in os.listdir(IMAGE_DIR) if f.endswith(".png")],
    key=lambda x: int(float(x.replace(".png", "")))
)

row_ids = []
embeddings = []

# ===============================
# EMBEDDING EXTRACTION
# ===============================
with torch.no_grad():
    for img_name in tqdm(image_files):
        row_id = int(float(img_name.replace(".png", "")))
        img_path = os.path.join(IMAGE_DIR, img_name)

        img = Image.open(img_path).convert("RGB")
        img = transform(img).unsqueeze(0).to(DEVICE)

        emb = model(img).cpu().numpy()[0]
        embeddings.append(emb)
        row_ids.append(row_id)

# ===============================
# SAVE
# ===============================
embeddings = np.vstack(embeddings)
np.save(OUTPUT_FILE, embeddings)
pd.DataFrame({"row_id": row_ids}).to_csv(META_FILE, index=False)

print("✅ Embeddings generated")
print("Shape:", embeddings.shape)  # (N, 2048)

